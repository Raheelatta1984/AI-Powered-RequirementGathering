import { createStore } from './store.mjs';
import { createApp } from './app.mjs';
import { seedDemo } from './demo.mjs';
import { runtimeConfig, configurationError } from './runtime-config.mjs';
const config = runtimeConfig(process.env);
if (config.problems.length) throw configurationError(config.problems);
const seed = !config.production && process.env.SEED_DEMO !== 'false' ? seedDemo : undefined;
const store = await createStore(config.dataDir, seed);
const app = createApp(store, { accessToken: config.token, secureCookies: config.secureCookies, publicOrigin: config.publicOrigin, proxyHops: config.proxyHops });
const server = app.listen(config.port, config.host, () => console.log(`Clarity workspace listening on ${config.host}:${config.port} · ${config.token ? 'protected workspace' : 'local demo workspace'} · ${process.env.ANTHROPIC_API_KEY ? 'AI enabled' : 'guided mode'}`));
for (const signal of ['SIGTERM', 'SIGINT']) process.on(signal, () => server.close(() => process.exit(0)));
